"""Generate build/irq_map.h for one PIC32MX part from model/pic32mx_sfr.json: IRQ (IFS/IEC bit) -> interrupt vector.
The model lists IRQs (cname per bit) and vectors (cname per vector) separately; several IRQs share a vector (a UART's
ERR/RX/TX, an SPI/I2C/UART that share pins). Join by normalised peripheral name; every IRQ must map or this fails.
Usage: python3 -I gen_irq_map.py <pic32mx_sfr.json> <part> <out.h>"""
import json
import re
import sys

ALIAS = {"FLASH_CONTROL": "FCE", "ETHERNET": "ETH", "USB": "USB_1", "PMP_ERROR": "PMP"}


def norm_irq(n: str) -> str:
    if n in ALIAS:
        return ALIAS[n]
    m = re.fullmatch(r"INPUT_CAPTURE_ERROR_(\d)", n)
    if m:
        return f"INPUT_CAPTURE_{m.group(1)}"
    n = re.sub(r"_(ERR|RX|TX|BUS|SLAVE|MASTER|ERROR|EVENT)$", "", n)
    m = re.fullmatch(r"([A-Z]+[0-9]?[A-Z]*?)(\d+[AB]?)", n)          # UART1A -> UART_1A, DMA0 -> DMA_0, I2C1 -> I2C_1
    if m and not n.startswith(("CORE", "INPUT", "OUTPUT", "TIMER", "EXTERNAL", "COMPARATOR", "CHANGE")):
        return f"{m.group(1)}_{m.group(2)}"
    return n


def main() -> int:
    src, part, out = sys.argv[1:4]
    d = json.load(open(src))
    vec_of = {}
    for v, cname, *_ in d["vectors"][part]:
        vec_of.setdefault(cname, v)
    irq_vec, missing = {}, []
    for irq, cname in d["irqs"][part]:
        k = norm_irq(cname)
        if k in vec_of:
            irq_vec.setdefault(irq, vec_of[k])
        elif irq not in irq_vec:
            missing.append((irq, cname, k))
    missing = [m for m in missing if m[0] not in irq_vec]
    if missing:
        print("unmapped IRQs:", missing, file=sys.stderr)
        return 1
    n = max(irq_vec) + 1
    with open(out, "w") as f:
        f.write(f"/* GENERATED by emu/ecu/tools/gen_irq_map.py from model/pic32mx_sfr.json for {part} -- do not edit */\n")
        f.write(f"#define PIC32_NIRQ {n}\n#define PIC32_NVEC {max(irq_vec.values()) + 1}\n")
        f.write("static const signed char IRQ_VEC[PIC32_NIRQ] = {")
        f.write(", ".join(str(irq_vec.get(i, -1)) for i in range(n)))
        f.write("};\n")
    print(f"{len(irq_vec)} IRQs -> {len(set(irq_vec.values()))} vectors for {part}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
