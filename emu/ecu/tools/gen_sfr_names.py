"""Generate build/sfr_names.h (address -> name, portal flag, power-on reset value) for one part from model/pic32mx_sfr.json.
Usage: python3 -I gen_sfr_names.py <pic32mx_sfr.json> <part> <out.h>"""
import json
import sys


def main() -> int:
    src, part, out = sys.argv[1:4]
    d = json.load(open(src))
    rows = sorted((int(s["addr"], 16), s["name"], bool(s.get("portals")), int(s.get("por", "0"), 16))
                  for s in d["sfrs"] if part in s["parts"])
    with open(out, "w") as f:
        f.write(f"/* GENERATED by emu/ecu/tools/gen_sfr_names.py from model/pic32mx_sfr.json for {part} -- do not edit */\n")
        f.write("typedef struct { unsigned addr; const char *name; int portals; unsigned por; } sfr_name_row;\n")
        f.write("static const sfr_name_row SFR_NAMES[] = {\n")
        for a, n, p, por in rows:
            f.write(f'  {{0x{a:08X}u, "{n}", {int(p)}, 0x{por:08X}u}},\n')
        f.write("};\n")
    print(f"{len(rows)} SFRs for {part}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
