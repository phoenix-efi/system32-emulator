#!/usr/bin/env python3
"""Generate build/sfr_reset.h (SFR names + POR values) from model/pic24fj256da210_sfr.json (generated from Microchip's
public device pack: scripts/gen_pic24_sfr.py). Build step only -- not used at run time."""
import json
import sys

m = json.load(open(sys.argv[1]))
rows = sorted({s['addr']: s for s in m['sfrs'] if 0x20 <= s['addr'] < 0x800}.values(), key=lambda s: s['addr'])
out = ['/* GENERATED by emu/pic24/tools/gen_sfr_reset.py from %s -- do not edit */' % sys.argv[1],
       'typedef struct { unsigned short addr, por; const char *name; } sfr_row;',
       'static const sfr_row SFR_ROWS[] = {']
for s in rows:
    out.append('  {0x%04X, 0x%04X, "%s"},' % (s['addr'], s['por'] & 0xFFFF, s['name']))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
