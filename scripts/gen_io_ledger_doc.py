"""Generate docs/io-ledger.md from model/io_ledger.json (and the package pinout in model/mcu_io.json).

    python3 -I scripts/gen_io_ledger_doc.py [--check]

--check regenerates in memory and fails if the committed page differs (make check-generated).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "io-ledger.md"
CATS = [("analog_sensor", "Analogue sensors"), ("engine_position", "Engine position"), ("switch_sense", "Switches and sense lines"),
        ("human_input", "Human inputs"), ("output", "Outputs"), ("bus", "Buses and devices"), ("power_reset", "Power and reset"),
        ("clock", "Clocks"), ("unused_pin", "Unused pins")]
BOARDS = [("ecu", "ECU board (each of ECU1 and ECU2)"), ("controller", "Cockpit Controller")]


def pkg_pins(part: dict) -> dict[str, int]:
    out = {}
    for n, names in part["pins"]:
        if n > 100:                                          # TQFP-100: package pins 1..100
            continue
        for nm in names:
            if re.fullmatch(r"R[A-G]\d+", nm):
                out[nm] = n
    return out


def cell(s) -> str:
    if isinstance(s, list):
        s = "<br>".join(str(x) for x in s)
    return str(s).replace("|", "\\|").replace("\n", " ")


def code(items: list[str]) -> str:
    return "<br>".join(f"`{x}`" for x in items) if items else "-"


def render(ledger: dict, mcu_io: dict) -> str:
    parts = {"ecu": mcu_io["parts"]["PIC32MX795F512L"], "controller": mcu_io["parts"]["PIC24FJ256DA210"]}
    pins = {b: pkg_pins(p) for b, p in parts.items()}
    sig = ledger["signals"]
    L = []
    w = L.append
    w("<!-- GENERATED by scripts/gen_io_ledger_doc.py from model/io_ledger.json -- do not hand-edit (make check-generated) -->")
    w("# I/O ledger")
    w("")
    w("Every way into and out of the target system's three MCUs -- each wire, sensor, switch, output, bus, supply and clock "
      "of the ECU board (two of them) and the Cockpit Controller -- with how the emulator models it physically, the faults "
      "it can inject, the knob that drives it and the test that exercises it. The source of truth is "
      "[`model/io_ledger.json`](../model/io_ledger.json); this page is "
      "generated from it.")
    w("")
    w("`make io-coverage` runs the firmware you supply over a scripted run set (cold boot, engine start / run / stop with every "
      "switch moved, every menu, SD map load and datalog, firmware-update entry, both SD slots, every fault knob) with the "
      "emulator's I/O coverage recorder on, and fails if the firmware touched an SFR module, pin or ADC channel that is not "
      "in the ledger, or if an entry marked modelled has no test. The harness model behind every knob is "
      "`emu/common/s32board.c`; `s32pair --knobs` lists the knobs and the browser bench reaches the same ones through "
      "`s32_wasm_knob(name, value)`.")
    w("")
    w("**Evidence:** DATASHEET (Microchip data sheet / device pack), DOCUMENTED (installation manual, drawings, operating "
      "procedures), OBSERVED (seen on the emulated system), MEASURED (on hardware), INFERRED (reasoned, not observed). "
      "**Modelled:** yes / partial / no. Package pins are the 100-pin TQFP numbering from the device packs "
      "(`model/mcu_io.json`).")
    w("")
    # summary
    w("## Summary")
    w("")
    w("| Category | ECU | Controller | Modelled yes | partial | no |")
    w("|---|---|---|---|---|---|")
    for cat, title in CATS:
        es = [e for e in sig if e["category"] == cat]
        if not es:
            continue
        c = Counter(e["modelled"] for e in es)
        w(f"| {title} | {sum(e['board'] == 'ecu' for e in es)} | {sum(e['board'] == 'controller' for e in es)} | "
          f"{c['yes']} | {c['partial']} | {c['no']} |")
    c = Counter(e["modelled"] for e in sig)
    w(f"| **All signals** | **{sum(e['board'] == 'ecu' for e in sig)}** | **{sum(e['board'] == 'controller' for e in sig)}** | "
      f"**{c['yes']}** | **{c['partial']}** | **{c['no']}** |")
    w("")
    ev = Counter(e["evidence"] for e in sig)
    w("Evidence of the signal entries: " + ", ".join(f"{k} {ev[k]}" for k in ("DATASHEET", "DOCUMENTED", "OBSERVED", "MEASURED", "INFERRED")) + ".")
    w("")
    for board, btitle in BOARDS:
        w(f"## {btitle}")
        w("")
        for cat, title in CATS:
            es = [e for e in sig if e["board"] == board and e["category"] == cat]
            if not es:
                continue
            w(f"### {title}")
            w("")
            w("| Signal | Connector | MCU pin (package) / peripheral | Electrical | Model | Faults | Knobs | Tests | Modelled | Evidence |")
            w("|---|---|---|---|---|---|---|---|---|---|")
            for e in es:
                p = [f"{x} ({pins[board][x]})" if x in pins[board] else x for x in e.get("mcu_pins", [])]
                pin = "<br>".join(p + [", ".join(e.get("adc", []))] if e.get("adc") else p) or "-"
                periph = e.get("peripheral", "")
                w(f"| **{cell(e['name'])}**<br>`{e['id']}` | {cell(e.get('connector', ''))} | {pin}"
                  f"{'<br>' + cell(periph) if periph else ''} | {cell(e.get('electrical', ''))} | {cell(e.get('model', ''))}"
                  f"{'<br>*' + cell(e['notes']) + '*' if e.get('notes') else ''} | {cell(', '.join(e.get('faults', [])) or '-')} | "
                  f"{code(e.get('knobs', []))} | {code(e.get('tests', []))} | {e['modelled']} | {e['evidence']} |")
            w("")
    w("## On-chip modules the firmware touches")
    w("")
    w("No external pin of their own; listed so the coverage gate can account for every SFR the firmware reads or writes.")
    w("")
    w("| Module | Board | SFR modules | Model | Tests | Evidence |")
    w("|---|---|---|---|---|---|")
    for e in ledger.get("on_chip", []):
        w(f"| {cell(e['name'])}<br>`{e['id']}` | {e['board']} | {', '.join(e['sfr_modules'])} | {cell(e['model'])}"
          f"{'<br>*' + cell(e['notes']) + '*' if e.get('notes') else ''} | {code(e.get('tests', []))} | {e['evidence']} |")
    w("")
    w("## Limits: what is modelled only in part")
    w("")
    for e in sig:
        if e["modelled"] != "yes":
            w(f"* **{e['name']}** (`{e['id']}`, {e['modelled']}): {e.get('notes') or e.get('model')}")
    w("")
    w("## Fault vocabulary")
    w("")
    for k, v in ledger["fault_vocabulary"].items():
        w(f"* `{k}`: {v}")
    w("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(json.loads((REPO / "model" / "io_ledger.json").read_text()), json.loads((REPO / "model" / "mcu_io.json").read_text()))
    if a.check:
        same = OUT.is_file() and OUT.read_text() == text
        print(f"{OUT}: {'matches' if same else 'DIFFERS from'} the generator output", file=sys.stderr)
        return 0 if same else 1
    OUT.write_text(text)
    print(f"{OUT}: written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
