"""Generate model/mcu_io.json -- package pinout, port-pin implementation and configuration-word fields of the two
MCUs in the target system -- from Microchip's device family packs (DFP).

    python3 scripts/gen_mcu_io.py [--check] [-o model/mcu_io.json]

Source of truth: the public DFPs, fetched by pinned URL and SHA-256 (scripts/dfp_fetch.py; never committed), the EDC
file of each part (`edc/<PART>.PIC`, XML):
  * `edc:PinList/edc:Pin` in document order = package pin 1..N; each pin's `edc:VirtualPin` names are its functions
    (port bit, analog channel, peripheral pins, remappable RPn pin);
  * `edc:DCRDef` = configuration words (address, factory default) with `edc:DCRFieldDef` fields laid out from bit 0
    (mask width, `edc:AdjustPoint` skips) and their `edc:DCRFieldSemantic` values.

The I/O ledger (model/io_ledger.json) cites package pins from this file, and the emulators' clock check decodes the
firmware image's configuration words with these field layouts. --check regenerates in memory and fails if the
committed file differs.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dfp_fetch import open_pack, pack_version  # noqa: E402

EDC = "{http://crownking/edc}"
PARTS = [  # (pack, part, role)
    ("Microchip.PIC32MX_DFP.1.7.380", "PIC32MX795F512L", "ECU"),
    ("Microchip.PIC24F-DA-GB_DFP.1.5.369", "PIC24FJ256DA210", "Cockpit Controller"),
]
WHEN = re.compile(r"\(field\s*&\s*(0x[0-9a-fA-F]+)\)\s*==\s*(0x[0-9a-fA-F]+)")


def _a(el: ET.Element, name: str, default=None):
    return el.get(EDC + name, default)


def _int(s: str) -> int:
    return int(s, 0)


def pins(root: ET.Element) -> list[list]:
    pl = root.find(f".//{EDC}PinList")
    out = []
    for n, p in enumerate(pl.findall(f"{EDC}Pin"), 1):
        out.append([n, [_a(v, "name") for v in p.findall(f"{EDC}VirtualPin")]])
    return out


def port_bits(pinlist: list[list]) -> dict[str, list[int]]:
    """Implemented port bits per port letter, from the pin names Rxn."""
    ports: dict[str, set[int]] = {}
    for _, names in pinlist:
        for nm in names:
            m = re.fullmatch(r"R([A-K])(\d+)", nm)
            if m:
                ports.setdefault(m.group(1), set()).add(int(m.group(2)))
    return {k: sorted(v) for k, v in sorted(ports.items())}


def config_words(root: ET.Element) -> list[dict]:
    out = []
    for d in root.iter(EDC + "DCRDef"):
        modes = d.findall(f"{EDC}DCRModeList/{EDC}DCRMode")
        if not modes:
            continue
        mode = next((m for m in modes if _a(m, "id") == "DS.0"), modes[0])
        fields, bit = [], 0
        for el in mode:
            tag = el.tag.replace(EDC, "")
            if tag == "AdjustPoint":
                bit += _int(_a(el, "offset", "0"))
            elif tag == "DCRFieldDef":
                w = _int(_a(el, "nzwidth", "1"))
                sem = []
                for s in el.findall(f"{EDC}DCRFieldSemantic"):
                    m = WHEN.search(_a(s, "when") or "")
                    if m:
                        sem.append([_a(s, "cname"), _int(m.group(2)), _a(s, "desc") or ""])
                fields.append({"name": _a(el, "cname") or _a(el, "name"), "lsb": bit, "width": w,
                               "desc": _a(el, "desc") or "", "values": sem})
                bit += w
        out.append({"name": _a(d, "cname") or _a(d, "name"), "addr": _a(d, "_addr"),
                    "default": _a(d, "default"), "fields": fields})
    return out


def build(packs: dict) -> dict:
    doc = {
        "_comment": "GENERATED by scripts/gen_mcu_io.py from the Microchip DFP EDC files (pack and sha256 below) -- do "
                    "not hand-edit. pins = [package pin, [function names]]; ports = implemented bits per port; "
                    "config_words = configuration words with fields {name, lsb, width, values [cname, value, desc]}. "
                    "Everything here is DOCUMENTED (vendor device file).",
        "parts": {},
    }
    for pack, part, role in PARTS:
        z = packs[pack]
        raw = z.read(f"edc/{part}.PIC")
        root = ET.fromstring(raw)
        pl = pins(root)
        doc["parts"][part] = {
            "role": role,
            "dfp": {"name": pack.rsplit(".", 3)[0], "version": pack_version(z),
                    "edc_sha256": hashlib.sha256(raw).hexdigest()[:16]},
            "pins": pl,
            "ports": port_bits(pl),
            "config_words": config_words(root),
        }
    return doc


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", type=Path, default=Path(__file__).resolve().parent.parent / "model" / "mcu_io.json")
    ap.add_argument("--check", action="store_true", help="fail if the committed file differs from a fresh generation")
    a = ap.parse_args(argv)
    packs = {pack: open_pack(pack) for pack, _, _ in PARTS}
    doc = build(packs)
    text = json.dumps(doc, indent=1, separators=(",", ":")) + "\n"
    if a.check:
        same = a.out.is_file() and a.out.read_text() == text
        print(f"{a.out}: {'matches' if same else 'DIFFERS from'} the generator output", file=sys.stderr)
        return 0 if same else 1
    a.out.write_text(text)
    for p, d in doc["parts"].items():
        print(f"{a.out}: {p}: {len(d['pins'])} pins, ports {''.join(d['ports'])}, {len(d['config_words'])} config words")
    return 0


if __name__ == "__main__":
    sys.exit(main())
