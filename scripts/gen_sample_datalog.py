"""Generate the browser bench's demo datalog ("Load Demo Climb (synthetic)") inside emu/wasm/web/s32_bench.js.

    python3 -I scripts/gen_sample_datalog.py [--check]

The rows are synthetic: a 40-second full-power climb on a six-cylinder engine followed by a power reduction, computed
from the formulas below (no randomness, no recorded flight). Only the column layout follows the Controller's
Datalog.CSV, so the page's CSV parser reads the snippet and a user's own log the same way.

--check regenerates in memory and fails if the committed page differs (make check-generated).
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PAGE = REPO / "emu" / "wasm" / "web" / "s32_bench.js"
BEGIN = "/* BEGIN generated by scripts/gen_sample_datalog.py: synthetic values, do not hand-edit */"
END = "/* END generated by scripts/gen_sample_datalog.py */"

# Datalog.CSV column layout (one name per column, in file order).
COLUMNS = [
    "Date", "Time", "RPM1", "RPM2", "MAP1", "MAP2", "IAT1", "IAT2", "TPS", "ENGTEMP", "AFR", "BATT1", "BATT2",
    "PUMP1", "PUMP2", "HP", "TORQUE", "INJ EN1", "INJ EN2", "PLEAD1", "PLEAD2", "FUEL FLOW", "FUEL TRIM",
    "INJ DUTY", "IGNITION", "T1S1", "T2S2",
]

ROWS = 40          # one row per second
REDUCE_AT = 28     # power reduction starts here


def row(i: int) -> list[str]:
    """Row i of the synthetic snippet, as Datalog.CSV fields."""
    w = math.sin(i * 0.7)                                   # small deterministic wobble
    climb = i < REDUCE_AT
    k = min(1.0, (i - REDUCE_AT) / 4.0) if not climb else 0.0   # 0 -> 1 over the reduction
    rpm = round(2700 - 200 * k + 6 * w)
    map1 = 29.1 - 0.025 * i - 3.4 * k                       # MAP falls with altitude, then with the throttle
    tps = round(100 - 32 * k)
    iat1 = 71 + i // 6
    et = 182 + round(i * 0.9)
    afr = 12.4 + 0.9 * k + 0.05 * w
    batt1 = 14.0 + 0.1 * math.sin(i * 0.3)
    ff = 0.000305 * map1 * rpm * (1.0 - 0.12 * k)           # gal/h, roughly proportional to airflow
    duty = ff * 1.35                                        # injector duty %
    adv = 25 + round((30.0 - map1) * 1.5)
    fields = [
        "06/15/2024", f"10:{12 + (i + 20) // 60:02d}:{(i + 20) % 60:02d}",
        str(rpm), str(rpm + (2 if i % 3 else 3)),
        f"{map1:.1f}", f"{map1 - 0.1:.1f}",
        str(iat1), str(iat1 + 3),
        str(tps), str(et), f"{afr:.1f}",
        f"{batt1:.1f}", f"{batt1 - 0.1:.1f}",
        "ON", "ON", "0", "0",
        "ON", "OFF", "ON", "ON",
        f"{ff:.1f}", "0", f"{duty:.1f}", str(adv),
        "Y/Y", "Y/Y",
    ]
    assert len(fields) == len(COLUMNS)
    return fields


def block() -> str:
    names = ", ".join(f'"{c}"' for c in COLUMNS)
    lines = [BEGIN, f"const DATALOG_COLUMNS = [{names}];", "const SAMPLE_DATALOG_ROWS = ["]
    lines += [f'  "{",".join(row(i))}",' for i in range(ROWS)]
    lines += ["];", END]
    return "\n".join(lines)


def render(page: str) -> str:
    a, b = page.find(BEGIN), page.find(END)
    if a < 0 or b < a:
        raise SystemExit(f"{PAGE}: generated-block markers not found")
    return page[:a] + block() + page[b + len(END):]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed page differs")
    a = ap.parse_args(argv)
    page = PAGE.read_text()
    new = render(page)
    if a.check:
        if new != page:
            print(f"{PAGE}: generated sample datalog is stale (run scripts/gen_sample_datalog.py)", file=sys.stderr)
            return 1
        print(f"{PAGE}: sample datalog up to date")
        return 0
    PAGE.write_text(new)
    print(f"{PAGE}: written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
